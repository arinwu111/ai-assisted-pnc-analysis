#!/usr/bin/env python3
from __future__ import annotations

import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "01-数据"
REPORT = ROOT / "04-报告"
REPORT.mkdir(parents=True, exist_ok=True)


def read_csv(name):
    with (DATA / name).open(encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


ping_rows = read_csv("平安产险_年度核心数据.csv")
peer_rows = read_csv("同行_年度承保指标.csv")
segment_rows = read_csv("平安产险_险种结构.csv")
all_rows = ping_rows + peer_rows


def find(entity, period, metric, scope="年度整体"):
    for r in all_rows:
        if r["entity"] == entity and r["period"] == period and r["metric"] == metric and r["scope"] == scope:
            return r
    raise KeyError((entity, period, metric, scope))


def source(r):
    return f"{r['source_file']}，{r['source_page']}，{r['source_table']}"


def fmt(x, decimals=1):
    return f"{x:.{decimals}f}"


out = []
fields = ["record_type", "period", "entity", "metric", "value", "unit", "status", "formula", "input_sources", "note"]


def add(record_type, period, entity, metric, value, unit, formula, sources, limit="", decimals=1):
    rendered = fmt(value, decimals)
    tag = f"【推算：{rendered}{unit}｜方法：{formula}｜输入来源：{sources}】"
    note = tag if not limit else f"{tag} {limit}"
    out.append({
        "record_type": record_type, "period": period, "entity": entity, "metric": metric,
        "value": rendered, "unit": unit, "status": "推算", "formula": formula,
        "input_sources": sources, "note": note,
    })


metrics = ("综合成本率", "费用率", "赔付率")
transitions = (("2022R", "2023"), ("2023", "2024"), ("2024", "2025"), ("2023", "2025"))
entities = ("平安产险", "人保财险", "太保产险")

for entity in entities:
    for start, end in transitions:
        for metric in metrics:
            a, b = find(entity, start, metric), find(entity, end, metric)
            improvement = float(a["value"]) - float(b["value"])
            sources = f"{source(a)}；{source(b)}"
            add("比率变动", f"{start}→{end}", entity, f"{metric}改善", improvement, "个百分点",
                f"{a['value']}%-{b['value']}%", sources,
                "正数表示改善，负数表示恶化；基于披露的一位小数，可受四舍五入影响。")

# Ping An's 2023-2025 COR improvement split.
p_cor = float(find("平安产险", "2023", "综合成本率")["value"]) - float(find("平安产险", "2025", "综合成本率")["value"])
p_exp = float(find("平安产险", "2023", "费用率")["value"]) - float(find("平安产险", "2025", "费用率")["value"])
p_loss = float(find("平安产险", "2023", "赔付率")["value"]) - float(find("平安产险", "2025", "赔付率")["value"])
p_sources = (f"{source(find('平安产险', '2023', '综合成本率'))}；"
             f"{source(find('平安产险', '2025', '综合成本率'))}")
add("平安COR贡献", "2023→2025", "平安产险", "费用率对COR改善的贡献占比", p_exp / p_cor * 100, "%",
    f"({29.2}-{26.4})/({100.7}-{96.8})×100", p_sources, "为算术拆解，不等同于因果归因。")
add("平安COR贡献", "2023→2025", "平安产险", "赔付率对COR改善的贡献占比", p_loss / p_cor * 100, "%",
    f"({71.5}-{70.4})/({100.7}-{96.8})×100", p_sources, "为算术拆解，不等同于因果归因。")


# Peer proxy for the industry-common expense compression. The proxy is a range, not a causal estimate.
for start, end in (("2023", "2024"), ("2024", "2025"), ("2023", "2025")):
    ping = float(find("平安产险", start, "费用率")["value"]) - float(find("平安产险", end, "费用率")["value"])
    picc = float(find("人保财险", start, "费用率")["value"]) - float(find("人保财险", end, "费用率")["value"])
    cpic = float(find("太保产险", start, "费用率")["value"]) - float(find("太保产险", end, "费用率")["value"])
    low = min(picc, cpic)
    high = min(max(picc, cpic), ping)
    central = min((picc + cpic) / 2, ping)
    sources = (f"{source(find('平安产险', start, '费用率'))}；{source(find('平安产险', end, '费用率'))}；"
               f"{source(find('人保财险', start, '费用率'))}；{source(find('人保财险', end, '费用率'))}；"
               f"{source(find('太保产险', start, '费用率'))}；{source(find('太保产险', end, '费用率'))}")
    common_limit = "只是同业共同费用压降代理，不可等同于纯粹的“报行合一”效应；太保2023费用率由COR减赔付率推算。"
    add("行业共同因素代理", f"{start}→{end}", "同业基准", "共同费用压降代理下限", low, "个百分点",
        f"min(人保费用率改善{picc:.1f},太保费用率改善{cpic:.1f})", sources, common_limit)
    add("行业共同因素代理", f"{start}→{end}", "同业基准", "共同费用压降代理上限", high, "个百分点",
        f"min(max(人保{picc:.1f},太保{cpic:.1f}),平安费用率改善{ping:.1f})", sources, common_limit)
    add("行业共同因素代理", f"{start}→{end}", "同业基准", "共同费用压降中性基准", central, "个百分点",
        f"min((人保{picc:.1f}+太保{cpic:.1f})/2,平安{ping:.1f})", sources, common_limit, decimals=2)
    add("行业共同因素代理", f"{start}→{end}", "平安产险", "共同因素占平安费用率改善份额_下限", low / ping * 100, "%",
        f"{low:.1f}/{ping:.1f}×100", sources, common_limit)
    add("行业共同因素代理", f"{start}→{end}", "平安产险", "共同因素占平安费用率改善份额_上限", high / ping * 100, "%",
        f"{high:.1f}/{ping:.1f}×100", sources, common_limit)
    add("行业共同因素代理", f"{start}→{end}", "平安产险", "共同因素占平安费用率改善份额_中性", central / ping * 100, "%",
        f"{central:.2f}/{ping:.1f}×100", sources, common_limit)


# Auto insurance's weight in 2025 insurance revenue.
auto = next(r for r in segment_rows if r["period"] == "2025" and r["scope"] == "车险" and r["metric"] == "保险服务收入")
total = find("平安产险", "2025", "保险服务收入")
auto_share = float(auto["value"]) / float(total["value"]) * 100
add("业务结构", "2025", "平安产险", "车险保险服务收入占比", auto_share, "%",
    f"{auto['value']}/{total['value']}×100", f"{source(auto)}；{source(total)}",
    "说明车险费用政策对整体的相关性；不能由此直接推出车险对整体费用率改善的精确贡献。")


out_path = DATA / "阶段3-1_COR拆解.csv"
with out_path.open("w", encoding="utf-8-sig", newline="") as f:
    w = csv.DictWriter(f, fieldnames=fields)
    w.writeheader()
    w.writerows(out)


