def reg_src(text, code="—"):
    text = " ".join(str(text).split())
    if text not in SRC_NUM:
        sid = f"S{len(SRC_ROWS)+1:02d}"
        SRC_NUM[text] = sid
        SRC_ROWS.append([sid, code, text])
    return SRC_NUM[text]


