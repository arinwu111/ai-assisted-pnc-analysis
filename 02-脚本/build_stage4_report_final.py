def strip_tags(t):
    t = re.sub(r"<br\s*/?>", "\n", t)
    t = re.sub(r"<span[^>]*>|</span>", "", t)
    return re.sub(r"<[^>]+>", lambda m: "**" if m.group(0) in ("<b>", "</b>") else "", t)


def mdt(t):
    """Markdown 正文：先压推算标签，再去 HTML 标签。"""
    return " ".join(strip_tags(refs(" ".join(str(t).split()), md=True)).split())


