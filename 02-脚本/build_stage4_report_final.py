# =============================================================== 推算清单收集与编号
# 注意：正文里的标签常跨行书写，“｜”与“方法／输入来源”之间可能夹换行或空格，
# 必须用 \s* 兜住；否则惰性匹配会跨过一个完整标签，把大段正文吞进“推算值”。
CALC_RE = re.compile(r"【推算：\s*([^【】]+?)\s*｜\s*方法：\s*([^【】]+?)\s*｜\s*输入来源：\s*([^【】]+?)\s*】", re.S)

CALC_ROWS = []         # [编号, 推算值, 方法, 输入来源]
CALC_ID = {}           # (推算值, 方法) → 编号


def _walk_strings(x):
    """按文档顺序遍历 BLOCKS 里的全部字符串（含表格行、列表项的嵌套）。"""
    if isinstance(x, str):
        yield x
    elif isinstance(x, (list, tuple)):
        for y in x:
            yield from _walk_strings(y)


def collect_calcs():
    """按正文出现顺序给推算编号；“同上”在附录里还原为上一条的输入来源。"""
    if CALC_ROWS:
        return CALC_ROWS
    prev = ""
    for b in BLOCKS:
        for t in _walk_strings(b):
            for m in CALC_RE.finditer(t):
                v, meth, src = (" ".join(x.split()) for x in m.groups())
                if src.startswith("同上"):
                    src = prev + src[2:]
                prev = src
                k = (v, meth)
                if k in CALC_ID:
                    continue
                cid = f"C{len(CALC_ROWS)+1:02d}"
                CALC_ID[k] = cid
                CALC_ROWS.append([cid, v, meth, src])
    return CALC_ROWS


def src_cell(text, md=False):
    """把一串“；”分隔的出处换成来源编号；非出处片段原样保留。"""
    ids, extra = [], []
    for part in [x.strip() for x in str(text).split("；") if x.strip()]:
        if part in SRC_NUM or ".pdf" in part or ".xls" in part or part.startswith("本报告假设"):
            ids.append(reg_src(part))
        else:
            extra.append(part)
    if md:
        out = "[" + "，".join(ids) + "]" if ids else ""
    else:
        out = ('<sup class="ref">[' + "，".join(f'<a href="#src-{i}">{i}</a>' for i in ids) + "]</sup>") if ids else ""
    return "；".join([x for x in [out] + extra if x])


def refs(t, md=False):
    """把正文中的【推算：…】压成“数值＋上标编号”，方法与输入来源只留在附录。"""
    collect_calcs()

    def rep(m):
        v, meth = (" ".join(x.split()) for x in m.groups()[:2])
        cid = CALC_ID[(v, meth)]
        if md:
            return f"{v}[{cid}]"
        return f'{v}<sup class="ref">[<a href="#calc-{cid}">{cid}</a>]</sup>'
    return CALC_RE.sub(rep, t)


